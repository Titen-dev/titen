// Prepares the Cloudflare Worker build:
//   worker/generated/pages.js  pre-rendered HTML pages (no file system on Workers)
//   worker/public/             static files with versioned imports + _headers for security/caching
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { assetVersions, renderPages, versionImports, PUBLIC_DIR } from '../web/server.js';
import { securityHeaders } from '../web/api.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT_PUBLIC = path.join(ROOT, 'worker', 'public');
const OUT_GENERATED = path.join(ROOT, 'worker', 'generated');

export function buildWorker({ frameAncestors = process.env.FRAME_ANCESTORS || '' } = {}) {
  const versions = assetVersions();
  const pages = renderPages(versions);

  fs.rmSync(OUT_PUBLIC, { recursive: true, force: true });
  fs.mkdirSync(OUT_PUBLIC, { recursive: true });
  fs.mkdirSync(OUT_GENERATED, { recursive: true });

  // Copy static files; JS gets its "./x.js" imports stamped with ?v=<hash> like the Node server does.
  const copy = (dir) => {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      const src = path.join(dir, e.name);
      const rel = path.relative(PUBLIC_DIR, src).split(path.sep).join('/');
      const dest = path.join(OUT_PUBLIC, rel);
      if (e.isDirectory()) {
        fs.mkdirSync(dest, { recursive: true });
        copy(src);
      } else if (rel.endsWith('.js')) {
        fs.writeFileSync(dest, versionImports(fs.readFileSync(src, 'utf8'), path.posix.dirname(rel), versions));
      } else {
        fs.copyFileSync(src, dest);
      }
    }
  };
  copy(PUBLIC_DIR);

  // Headers for static files (Workers Static Assets reads this file).
  const sec = Object.entries(securityHeaders(frameAncestors)).map(([k, v]) => `  ${k}: ${v}`).join('\n');
  fs.writeFileSync(
    path.join(OUT_PUBLIC, '_headers'),
    `/*\n${sec}\n/assets/*\n  Cache-Control: public, max-age=31536000, immutable\n/favicon.svg\n  Cache-Control: public, max-age=86400\n`
  );

  fs.writeFileSync(path.join(OUT_GENERATED, 'pages.js'), `// Generated by scripts/build-worker.mjs. Do not edit.\nexport default ${JSON.stringify(pages)};\n`);
  return { pages: Object.keys(pages), files: fs.readdirSync(OUT_PUBLIC, { recursive: true }).length };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const r = buildWorker();
  console.log(`Built worker: ${r.pages.length} pages, ${r.files} static entries → worker/`);
}
